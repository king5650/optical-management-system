import sys
from PyQt6.QtWidgets import QApplication
from PyQt6.QtGui import QPainter, QFont, QColor, QPen
from PyQt6.QtPrintSupport import QPrinter

def draw_prescription_form_with_qpainter(output_path="prescription_form_qpainter12.pdf"):
    app = QApplication(sys.argv)  # Required for any Qt app

    printer = QPrinter(QPrinter.PrinterMode.HighResolution)
    printer.setOutputFormat(QPrinter.OutputFormat.PdfFormat)
    printer.setOutputFileName(output_path)

    painter = QPainter()
    if not painter.begin(printer):
        print("Failed to open printer for painting.")
        return
    
    margin = 80
    line_spacing = 30
    y = margin

    # Header
    # painter.setFont(QFont("Helvetica", 18, QFont.Weight.Bold))
    # painter.drawText(margin, y, "NGASSAM OPTIQUE - Medical Report")
    # y += 2 * line_spacing
    # # Header
    painter.setFont(QFont("Helvetica", 40, QFont.Weight.Bold))
    painter.setPen(QColor("red"))
    painter.drawText(margin + 1400, y + 390, "NGASSAM OPTIQUE")
    
    painter.setFont(QFont("Helvetica-Bold", 13))
    painter.setPen(QColor("black"))
    painter.drawText(margin + 1900, y + 700, "Situé à l'Avenue Kennedy derrière ADAMAOUA PALACE")
    painter.drawText(margin + 1990, y + 950, "Tél.: (237) 699 67 50 25 / 620 37 69 38 / 671 16 65 27")
    
    painter.drawText(margin + 50, y + 20, "Situé à l'Avenue Kennedy derrière ADAMAOUA PALACE")
    painter.drawText(margin + 50, y + 50, "Tél.: (237) 699 67 50 25 / 620 37 69 38 / 671 16 65 27")

    painter.setFont(QFont("Helvetica-Bold", 13, italic=True))
    painter.setPen(QColor("red"))
    painter.drawText(margin + 3000, y + 1200, "Le professionnel de la santé visuelle")
    painter.drawText(margin + 100, y + 20, "Situé à l'Avenue Kennedy derrière ADAMAOUA PALACE")
    painter.drawText(margin + 100, y + 50, "Tél.: (237) 699 67 50 25 / 620 37 69 38 / 671 16 65 27")
    # Separator Line
    # painter.setPen(QColor("black"))
    painter.setPen(QPen(QColor("black"), 30))
    painter.drawLine(700, 1390, 9000, 1390)

    painter.setFont(QFont("Helvetica-Bold", 13, QFont.Weight.Bold))
    painter.setPen(QColor("red"))
    painter.drawText(margin + 3000, y + 1600, "ORDONNANCE DE LUNETTES")
    y += line_spacing 
    
    painter.setPen(QColor("black"))
    painter.setFont(QFont("Helvetica", 10, QFont.Weight.Bold))
    painter.drawText(margin + 7500, y + 1920, "Date: ")

    # Patient Info
    painter.setPen(QColor("black"))
    painter.setFont(QFont("Helvetica", 11, QFont.Weight.Bold))
    painter.drawText(margin + 500, y + 2220, "Noms et Prénoms :")
    painter.drawText(margin + 500, y + 2690, "Age :")
    painter.drawText(margin + 2000, y + 2690, "Sexe :")
    painter.drawText(margin + 5000, y + 2690, "Profession :")


    # Table
    table_x = 500
    table_y = 3300
    col_width = 1700
    row_height = 600
    headers = ["œil", "Sphère", "Cyl", "Axe", "Addition"]
    rows = [["OD", "", "", "", ""], ["OG", "", "", "", ""]]

    painter.setFont(QFont("Helvetica", 10, QFont.Weight.Bold))
    for col_index, header in enumerate(headers):
        painter.drawText(table_x + col_index * col_width + 400, table_y + 400, header)

    painter.setFont(QFont("Helvetica", 10))
    for row_index, row in enumerate(rows):
        for col_index, cell in enumerate(row):
            painter.drawText(table_x + col_index * col_width + 400,
                             table_y + (row_index + 1) * row_height + 400, cell)

    # Draw table grid
    for r in range(len(rows) + 1 + 1):
        painter.drawLine(table_x, table_y + r * row_height,
                         table_x + len(headers) * col_width, table_y + r * row_height)
    for c in range(len(headers) + 1):
        painter.drawLine(table_x + c * col_width, table_y,
                         table_x + c * col_width, table_y + (len(rows) + 1) * row_height)


    # Footer
    # painter.setPen(QPen(QColor("gray")))
    # painter.drawText(margin, y, "Generated by NGASSAM OPTIQUE | Confidential")
    # y += line_spacing
    # painter.drawText(margin, y, f"Date: ")
    # y += line_spacing
    # painter.drawText(margin, y, "Thank you for choosing NGASSAM OPTIQUE!")
    painter.end()
    print(f"Prescription form saved to {output_path}")

    # Close the app
    sys.exit(app.exec())



# Run it
draw_prescription_form_with_qpainter("prescription_form_qpainter12.pdf")




